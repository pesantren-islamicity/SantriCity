/**
 * Calculates tenure statistics for a given santri
 */
export function calculateSantriTenureSummary(
  santri: SantriProfile,
  milestones: GrowthMilestone[]
): SantriTenureSummary {
  const santriMilestones = milestones.filter((m) => m.santriId === santri.id);
  const completed = santriMilestones.filter((m) => m.status === 'Tercapai').length;
  const inProgress = santriMilestones.filter((m) => m.status === 'Sedang Berjalan').length;
  const future = santriMilestones.filter((m) => m.status === 'Proyeksi Masa Depan').length;
  const total = santriMilestones.length;

  const completionRate = total > 0 ? Math.round((completed / total) * 100) : 0;

  // Derive tenure duration based on entry year
  let tenureDuration = '2 Tahun 3 Bulan';
  let entryDate = 'Juli 2024';
  let projectedGraduationDate = 'Juli 2027';

  if (santri.angkatan?.includes('2025')) {
    tenureDuration = '1 Tahun 3 Bulan';
    entryDate = 'Juli 2025';
    projectedGraduationDate = 'Juli 2028';
  } else if (santri.angkatan?.includes('2023')) {
    tenureDuration = '3 Tahun 3 Bulan';
    entryDate = 'Juli 2023';
    projectedGraduationDate = 'Juli 2026';
  }

  return {
    santriId: santri.id,
    tenureDuration,
    entryDate,
    projectedGraduationDate,
    totalMilestones: total,
    completedMilestones: completed,
    inProgressMilestones: inProgress,
    futureMilestones: future,
    completionRate,
    tahfidzJuzProgress: {
      start: 2,
      current: santri.capaianJuz || 18.5,
      target: santri.targetJuz || 30,
    },
    gpaProgress: {
      year1: 91.8,
      year2: 92.8,
      current: 93.2,
    },
  };
}
